from datetime import UTC, date, datetime

from scm_ml.synthetic import SyntheticWorld
from scm_ml.synthetic.sql_export import BATCH_ROWS, insert, literal, render


def test_literals_are_quoted_for_postgres() -> None:
    assert literal(None) == "NULL"
    assert literal(True) == "TRUE"
    assert literal(12) == "12" and literal(0.343) == "0.343"
    assert literal("O'Neil") == "'O''Neil'"
    assert literal(date(2024, 12, 30)) == "'2024-12-30'"
    assert literal(datetime(2024, 12, 30, 8, tzinfo=UTC)) == "'2024-12-30T08:00:00+00:00'"
    assert literal(("ISO9001", "RoHS")) == "ARRAY['ISO9001', 'RoHS']::text[]"
    assert literal(()) == "ARRAY[]::text[]"


def test_inserts_are_batched_and_idempotent() -> None:
    rows = [(i, f"n{i}") for i in range(BATCH_ROWS * 2 + 1)]
    statements = insert("t", ["a", "b"], rows)
    assert len(statements) == 3
    assert all(s.endswith("ON CONFLICT DO NOTHING;") for s in statements)
    assert statements[0].count("\n  (") == BATCH_ROWS


def test_refreshed_columns_overwrite_an_existing_row() -> None:
    [statement] = insert(
        "sku", ["sku_id", "name"], [("SKU-001", "Wireless earbuds")], ("sku_id", ["name"])
    )
    assert statement.endswith("ON CONFLICT (sku_id) DO UPDATE SET name = EXCLUDED.name;")


def test_seed_covers_the_tables_the_api_serves(small_world: SyntheticWorld) -> None:
    script = render(small_world)
    assert script.startswith("-- Generated by") and script.rstrip().endswith("COMMIT;")
    for table in [
        "region",
        "sku",
        "supplier",
        "warehouse",
        "fulfillment_lane",
        "supplier_contract",
        "supplier_offer",
        "supplier_offer_shipping",
        "inventory_position",
        "purchase_order",
        "demand_observation",
        "knowledge_document",
    ]:
        assert f"INSERT INTO {table} (" in script, table
    assert "INSERT INTO sales_order" not in script
    assert render(small_world) == script  # deterministic
