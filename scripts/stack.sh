#!/usr/bin/env bash
# Local stack: `scripts/stack.sh up|smoke|down|reset|logs|ps`.
set -euo pipefail
cd "$(dirname "$0")/.."

random() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }

ensure_env() {
  [[ -f .env ]] && return
  cp .env.example .env
  {
    echo
    echo "# Generated by scripts/stack.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ); local use only."
    echo "POSTGRES_PASSWORD=$(random 16)"
    echo "SCM_JWT_SECRET=$(random 32)"
    echo "SCM_ML_INTERNAL_TOKEN=$(random 24)"
    echo "SCM_DEMO_PASSWORD=demo-$(random 6)"
  } >> .env
  echo "created .env with random local secrets"
}

case "${1:-up}" in
  up)
    ensure_env
    docker compose up --build --detach --wait
    password=$(grep '^SCM_DEMO_PASSWORD=' .env | tail -1 | cut -d= -f2-)
    frontend_port=$(grep '^FRONTEND_PORT=' .env | tail -1 | cut -d= -f2-)
    echo
    echo "Stack is up: http://localhost:${frontend_port:-3000}"
    echo "Sign in as planner, manager, finance or admin with password: ${password}"
    ;;
  smoke)
    export SCM_SMOKE_URL="http://localhost:$(grep '^FRONTEND_PORT=' .env | tail -1 | cut -d= -f2-)"
    export SCM_SMOKE_PASSWORD="$(grep '^SCM_DEMO_PASSWORD=' .env | tail -1 | cut -d= -f2-)"
    uv run pytest tests/smoke -m smoke -v
    ;;
  down) docker compose down ;;
  reset) docker compose down --volumes ;;
  logs) docker compose logs --follow "${@:2}" ;;
  ps) docker compose ps --all ;;
  *) echo "usage: $0 up|smoke|down|reset|logs|ps" >&2; exit 2 ;;
esac
